import asyncio
import json
import logging
import time
from dataclasses import dataclass
from datetime import datetime, timezone

from pydantic import ValidationError

from app.config import Settings, estimate_cost
from app.exceptions import LLMError, LLMNotConfiguredError
from app.schemas import AnalysisMeta, LinkAnalysisResponse, LLMAnalysisOutput
from app.services.competitor_service import CompetitorService
from app.services.llm_service import BaseLLMClient
from app.services.prompts import SYSTEM_PROMPT, build_repair_prompt, build_user_prompt
from app.services.website_extractor import WebsiteExtractor
from app.utils.cache import TTLCache
from app.utils.validators import normalize_url

logger = logging.getLogger(__name__)

SEARCH_VOLUME_NOTE = (
    "Search volumes and rankings are intentionally not included - no search-volume data source "
    "is connected, so the queries are relevance-based suggestions only."
)


@dataclass
class _Usage:
    input_tokens: int = 0
    output_tokens: int = 0
    latency_ms: int = 0
    calls: int = 0

    def add(self, result) -> None:
        self.input_tokens += result.input_tokens or 0
        self.output_tokens += result.output_tokens or 0
        self.latency_ms += result.latency_ms
        self.calls += 1


class AnalysisService:
    def __init__(
        self,
        extractor: WebsiteExtractor,
        competitor_service: CompetitorService,
        llm_clients: list[BaseLLMClient],
        settings: Settings,
        cache: TTLCache | None = None,
    ):
        if not llm_clients:
            raise ValueError("At least one LLM client is required")
        self.extractor = extractor
        self.competitors = competitor_service
        self.llm_clients = llm_clients
        self.settings = settings
        # explicit None check - an empty TTLCache is falsy because it defines __len__
        self.cache = cache if cache is not None else TTLCache(0)
        # URL -> running analysis, so identical requests arriving together share one LLM call
        self._in_flight: dict[str, asyncio.Task] = {}

    async def analyze(self, raw_url: str) -> LinkAnalysisResponse:
        started = time.perf_counter()
        url = normalize_url(raw_url)

        cached = self.cache.get(url)
        if cached is not None:
            logger.info("Cache hit for %s", url)
            return self._reuse(cached, started)

        running = self._in_flight.get(url)
        if running is not None:
            logger.info("Joining analysis already in progress for %s", url)
            return self._reuse(await asyncio.shield(running), started)

        task = asyncio.ensure_future(self._analyze(url, started))
        # mark the exception as retrieved even if every waiter has gone away
        task.add_done_callback(lambda t: t.cancelled() or t.exception())
        self._in_flight[url] = task
        try:
            # shield: if this client disconnects, others waiting on the same URL still get a result
            return await asyncio.shield(task)
        finally:
            if task.done():
                self._in_flight.pop(url, None)
            else:
                task.add_done_callback(lambda _: self._in_flight.pop(url, None))

    @staticmethod
    def _reuse(response: LinkAnalysisResponse, started: float) -> LinkAnalysisResponse:
        copy = response.model_copy(deep=True)
        copy.meta.cached = True
        copy.meta.total_duration_ms = int((time.perf_counter() - started) * 1000)
        return copy

    async def _analyze(self, url: str, started: float) -> LinkAnalysisResponse:
        content = await self.extractor.extract(url)
        user_prompt = build_user_prompt(
            content.to_prompt(self.settings.max_content_chars),
            content.seo_audit.issues if content.seo_audit else [],
        )

        output, usage, client, used_fallback = await self._run_llm(user_prompt)

        brand = output.brand
        brand.social_profiles = content.social_profiles
        brand.contact_emails = content.contact_emails
        brand.contact_phones = content.contact_phones

        analysis = output.analysis
        analysis.seo_improvements.current_seo_audit = content.seo_audit
        analysis.competitor_analysis = await self.competitors.enrich(
            analysis.competitor_analysis, content.final_url, output.brand.name
        )

        notes = [SEARCH_VOLUME_NOTE, *content.warnings]
        inferred = [s.service_name for s in analysis.top_services if s.source == "inferred"]
        if inferred:
            notes.append(
                "These services were inferred and are not explicitly listed on the website: " + ", ".join(inferred)
            )
        if used_fallback:
            notes.append(f"Primary LLM failed; result generated by fallback model {client.model}.")

        response = LinkAnalysisResponse(
            website=content.final_url,
            brand=brand,
            analysis=analysis,
            meta=AnalysisMeta(
                llm_provider=client.provider,
                llm_model=client.model,
                used_fallback=used_fallback,
                pages_analyzed=content.pages_analyzed,
                input_tokens=usage.input_tokens or None,
                output_tokens=usage.output_tokens or None,
                estimated_cost_usd=estimate_cost(client.model, usage.input_tokens, usage.output_tokens),
                llm_latency_ms=usage.latency_ms,
                total_duration_ms=int((time.perf_counter() - started) * 1000),
                cached=False,
                generated_at=datetime.now(timezone.utc),
                notes=notes,
            ),
        )

        self.cache.set(url, response)
        logger.info(
            "Analysed %s with %s/%s in %d ms (tokens in=%s out=%s, cost=$%s)",
            url,
            client.provider,
            client.model,
            response.meta.total_duration_ms,
            usage.input_tokens,
            usage.output_tokens,
            response.meta.estimated_cost_usd,
        )
        return response

    async def _run_llm(self, user_prompt: str):
        failures = []
        for index, client in enumerate(self.llm_clients):
            try:
                output, usage = await self._generate_validated(client, user_prompt)
                return output, usage, client, index > 0
            except (LLMError, LLMNotConfiguredError) as exc:
                logger.warning("LLM %s/%s failed: %s", client.provider, client.model, exc.message)
                failures.append((client, exc))

        if all(isinstance(exc, LLMNotConfiguredError) for _, exc in failures):
            raise LLMNotConfiguredError(
                "No LLM API key is configured. Set GEMINI_API_KEY (or another provider key) in the .env file."
            )
        # Report the real failure, not "fallback has no key"
        real_error = next(e for _, e in failures if not isinstance(e, LLMNotConfiguredError))
        summary = "; ".join(f"{c.provider}/{c.model}: {e.message}" for c, e in failures)
        raise LLMError(
            f"The analysis could not be generated. {summary}",
            code=real_error.code,
            status_code=real_error.status_code,
        )

    async def _generate_validated(self, client: BaseLLMClient, user_prompt: str):
        usage = _Usage()
        result = await client.generate_json(SYSTEM_PROMPT, user_prompt)
        usage.add(result)
        try:
            return LLMAnalysisOutput.model_validate(result.data), usage
        except ValidationError as exc:
            logger.info("LLM output failed validation (%d errors), asking for a repair", exc.error_count())
            errors = _format_errors(exc)

        repair_prompt = build_repair_prompt(json.dumps(result.data, ensure_ascii=False)[:20000], errors)
        repaired = await client.generate_json(SYSTEM_PROMPT, repair_prompt)
        usage.add(repaired)
        try:
            return LLMAnalysisOutput.model_validate(repaired.data), usage
        except ValidationError as exc:
            raise LLMError(
                f"The model output did not match the expected structure: {_format_errors(exc, limit=3)}",
                code="llm_invalid_output",
            ) from None


def _format_errors(exc: ValidationError, limit: int = 15) -> str:
    lines = []
    for error in exc.errors()[:limit]:
        location = ".".join(str(part) for part in error["loc"])
        lines.append(f"- {location}: {error['msg']}")
    return "\n".join(lines)
